#!/usr/bin/env bash
# billing-sim.sh — the B0 local Stripe-sim orchestrator (billing epic).
#
# Brings up `stripe/stripe-mock` (the spec-valid Stripe API mock) on loopback, writes
# the endpoint-override env contract to a sourceable file, and tears it down on every
# exit path. Idempotent. The webhook-signing correctness lives in the Rust injector
# (`tests/common/stripe_sim.rs`) — this script is the substrate + tiers around it.
#
# Subcommands:
#   up            stand up stripe-mock, wait for readiness, write the env file. Idempotent.
#   down          tear stripe-mock down (docker compose down -v). No-op if already down.
#   env           print the env contract (also written to the env file by `up`)
#   test-l1       Level-1 fail-closed tier: guard → up → Stripe contract smoke
#                 (Customer create+retrieve, Price list, Checkout Session create,
#                 Portal Session create, meter_events ack) → down.
#   test-l2       Level-2 full-flow-local tier: guard → up → the Rust `billing::` tier
#                 (checkout-create → inject signed webhook → placeholder consumer
#                 verify+dispatch → dunning → meter push) under CYTO_TEST_NO_SKIP=1 → down.
#
# PROV-B0-1 (substrate), PROV-B0-4 (env contract), PROV-B0-5 (L1/L2 tiers),
# PROV-B0-6 (guard runs first).
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
COMPOSE="$ROOT/src-app/billing-sim/docker-compose.billing-sim.yaml"
ENV_FILE="${CYTO_BILLING_SIM_ENV_FILE:-$ROOT/src-app/billing-sim/.billing-sim.env}"
GUARD="$ROOT/scripts/billing-sim-guard.sh"

# --- the canonical endpoint-override env contract (PROV-B0-4) ----------------
HTTP_PORT="${CYTO_BILLING_SIM_HTTP_PORT:-12111}"
HTTPS_PORT="${CYTO_BILLING_SIM_HTTPS_PORT:-12112}"
STRIPE_API_BASE_LOCAL="http://127.0.0.1:${HTTP_PORT}"
# These three are FIXED TEST CONSTANTS (DEC-10). The whsec MUST equal
# DEFAULT_TEST_WHSEC in tests/common/stripe_sim.rs so the Rust injector + shell tiers
# agree byte-for-byte; the key MUST equal DUMMY_KEY in billing-sim-guard.sh.
WEBHOOK_SECRET_LOCAL="whsec_b0_local_test_secret"
SECRET_KEY_LOCAL="sk_test_local"

say() { echo "[billing-sim] $*" >&2; }
die() { echo "[billing-sim] FAIL: $*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "'$1' not on PATH${2:+ — $2}"; }
compose() { docker compose -f "$COMPOSE" "$@"; }

wait_mock() {
  # stripe-mock answers a spec GET immediately once serving. Any key works.
  local i
  for i in $(seq 1 60); do
    if curl -fsS --max-time 2 -o /dev/null -u "${SECRET_KEY_LOCAL}:" \
         "$STRIPE_API_BASE_LOCAL/v1/customers?limit=1" 2>/dev/null; then
      return 0
    fi
    sleep 1
  done
  return 1
}

write_env_file() {
  cat > "$ENV_FILE" <<EOF
# GENERATED by scripts/billing-sim.sh — the B0 endpoint-override env contract (PROV-B0-4).
# Source it to point billing code at the local Stripe sim substrate:
#   set -a; source src-app/billing-sim/.billing-sim.env; set +a
# Loopback-only + fixed dummy test constants — no real Stripe, no network (INV-1).
# B2/B3 READ these; a release binary honors STRIPE_API_BASE/_WEBHOOK_SECRET only as a
# #[cfg(debug_assertions)] test seam (DEC-6), never in production.
export STRIPE_API_BASE=$STRIPE_API_BASE_LOCAL
export STRIPE_WEBHOOK_SECRET=$WEBHOOK_SECRET_LOCAL
export STRIPE_SECRET_KEY=$SECRET_KEY_LOCAL
EOF
  # TEST-7 post-condition (PROV-B0-4): after `up`, the documented env contract is
  # exported with the sim values (loopback base + the local whsec + the dummy key).
  grep -q "STRIPE_API_BASE=$STRIPE_API_BASE_LOCAL" "$ENV_FILE" || die "TEST-7: STRIPE_API_BASE not written to $ENV_FILE"
  grep -q "STRIPE_WEBHOOK_SECRET=$WEBHOOK_SECRET_LOCAL" "$ENV_FILE" || die "TEST-7: STRIPE_WEBHOOK_SECRET not written to $ENV_FILE"
  grep -q "STRIPE_SECRET_KEY=$SECRET_KEY_LOCAL" "$ENV_FILE" || die "TEST-7: STRIPE_SECRET_KEY not written to $ENV_FILE"
  say "wrote env contract → $ENV_FILE"
}

print_env() {
  cat <<EOF
STRIPE_API_BASE=$STRIPE_API_BASE_LOCAL
STRIPE_WEBHOOK_SECRET=$WEBHOOK_SECRET_LOCAL
STRIPE_SECRET_KEY=$SECRET_KEY_LOCAL
EOF
}

cmd_up() {
  need docker; need curl
  [ -f "$COMPOSE" ] || die "compose file missing: $COMPOSE"
  say "bringing up stripe-mock …"
  compose up -d >/dev/null 2>&1 || die "docker compose up failed"
  say "waiting for stripe-mock ($STRIPE_API_BASE_LOCAL) …"
  wait_mock || { compose logs --tail 30 stripe-mock >&2; die "stripe-mock did not become ready"; }
  write_env_file
  say "UP. stripe-mock ready. Source the env: 'set -a; source $ENV_FILE; set +a'"
}

cmd_down() {
  need docker
  if [ -f "$COMPOSE" ]; then compose down -v --remove-orphans >/dev/null 2>&1 || true; fi
  rm -f "$ENV_FILE" 2>/dev/null || true
  # VERIFY — never print DOWN over a survivor (TEST-8).
  if docker ps -aq --filter "label=com.docker.compose.project=cyto-billing-sim" 2>/dev/null | grep -q .; then
    say "WARN: cyto-billing-sim container(s) SURVIVED teardown — 'docker compose -f $COMPOSE down -v' by hand."
    return 1
  fi
  say "DOWN. stripe-mock removed."
  return 0
}

# --- Level-1 Stripe contract smoke (spec-valid responses from the mock) ------
# Each helper hits a real stripe-mock endpoint with the DUMMY key and asserts a
# spec-valid `object`. No real key, no network beyond loopback.
mock_get() { curl -fsS --max-time 5 -u "${SECRET_KEY_LOCAL}:" "$STRIPE_API_BASE_LOCAL$1" 2>/dev/null; }
mock_post() { curl -fsS --max-time 5 -u "${SECRET_KEY_LOCAL}:" -X POST "$STRIPE_API_BASE_LOCAL$1" "${@:2}" 2>/dev/null; }
assert_object() {
  # $1 = json body, $2 = expected "object" value, $3 = label. Returns non-zero on
  # mismatch (does NOT `die`) so the caller's `|| rc=1` accumulate-and-continue works
  # and the tier reports a real PASS/FAIL summary.
  if ! printf '%s' "$1" | grep -q "\"object\": *\"$2\""; then
    say "l1 smoke: $3 did NOT return object=$2"
    return 1
  fi
  say "l1 smoke: $3 OK (object=$2)"
  return 0
}

# TEST-1 (the INV-1 Level-1 tier) + TEST-8 (down leaves zero containers; a second up is
# idempotent — covered by the trap teardown + the explicit final down below).
cmd_test_l1() {
  need docker; need curl
  # FAIL-CLOSED loud-skip contract: the guard runs FIRST on the AMBIENT env; a real
  # Stripe cred/endpoint fails the tier (never a silent skip). Mirrors `test-sandbox`.
  echo "[billing-sim-test-l1] guard: refusing any real Stripe credential/endpoint (INV-1)"
  bash "$GUARD" || die "no-real-Stripe guard REFUSED the env — a real Stripe key/endpoint is present (INV-1)"

  # Cross-implementation byte-exactness proof (PROV-B0-2): the Node (OpenSSL) signer
  # must agree with the Rust injector's known-answer vector. Run it here so the
  # independent oracle is actually EXERCISED by a tier, not only by a hand-run.
  if command -v node >/dev/null 2>&1; then
    node "$ROOT/scripts/stripe-sign.mjs" --selftest || die "stripe-sign.mjs selftest FAILED — the Node(OpenSSL) signer diverged from the byte-exact KAT the Rust injector uses."
  else
    say "WARN: node not on PATH — skipping the cross-impl signer selftest (the Rust KAT test still runs in L2)."
  fi

  local rc=0
  # teardown on EVERY exit path. The EXIT trap covers normal + `die`. The INT/TERM
  # trap disarms EXIT so teardown runs exactly once, then aborts (never resumes the
  # tier body against a destroyed substrate). Same shape as cloud-sim.sh.
  trap 'cmd_down' EXIT
  trap 'trap - EXIT INT TERM; cmd_down; exit 130' INT TERM
  cmd_up
  echo "[billing-sim-test-l1] --- Stripe contract smoke against stripe-mock ---"
  # Customer create + retrieve
  assert_object "$(mock_post /v1/customers -d 'email=b0@example.test')" customer "customer create" || rc=1
  assert_object "$(mock_get /v1/customers/cus_probe)" customer "customer retrieve" || rc=1
  # Price list (a `list` object)
  assert_object "$(mock_get '/v1/prices?limit=1')" list "price list" || rc=1
  # Checkout Session create
  assert_object "$(mock_post /v1/checkout/sessions -d mode=subscription -d 'line_items[0][price]=price_x' -d 'line_items[0][quantity]=1' -d 'success_url=https://x.test/s' -d 'cancel_url=https://x.test/c')" checkout.session "checkout session create" || rc=1
  # Billing Portal Session create
  assert_object "$(mock_post /v1/billing_portal/sessions -d customer=cus_probe -d 'return_url=https://x.test/r')" billing_portal.session "portal session create" || rc=1
  # Billing Meter Events ack (PROV-B0-3 contract half — the mock SERVES the endpoint)
  assert_object "$(mock_post /v1/billing/meter_events -d event_name=compute_seconds -d 'payload[stripe_customer_id]=cus_probe' -d 'payload[value]=10')" billing.meter_event "meter_events ack" || rc=1

  # TEST-8 idempotency: a second `up` on a live stack must be a no-op, not an error.
  echo "[billing-sim-test-l1] idempotency: re-running up on a live stack …"
  cmd_up || rc=1

  # Explicit teardown on the NORMAL path so a teardown FAILURE (survivor) fails the
  # tier — an EXIT-trap body's non-zero return does not flip the script's exit status
  # (TEST-8). Disarm the trap first.
  trap - INT TERM EXIT
  cmd_down || { echo "[billing-sim-test-l1] FAIL: teardown left containers"; rc=1; }
  if [ "$rc" -eq 0 ]; then echo "[billing-sim-test-l1] PASS"; else echo "[billing-sim-test-l1] FAIL"; fi
  return "$rc"
}

# $1 (optional): cargo feature args, e.g. "--features saas". Default empty (the
# saas-OFF tier: B0's `l2_full_flow_local` placeholder loop + the injector self-tests
# + the saas-gating source-grep). With `--features saas` the whole `#[cfg(feature =
# "saas")]` B1–B4 billing acceptance tier (checkout/portal/webhook/quota/…) ALSO
# compiles + runs against the live mock — the hosted leg of B5's dual-config matrix.
cmd_test_l2() {
  need docker; need curl; need cargo
  local feature_args="${1:-}"
  local label="billing-sim-test-l2"
  [ -n "$feature_args" ] && label="billing-sim-test-l2-saas"
  echo "[$label] guard: refusing any real Stripe credential/endpoint (INV-1)"
  bash "$GUARD" || die "no-real-Stripe guard REFUSED the env — a real Stripe key/endpoint is present (INV-1)"

  local rc=0
  trap 'cmd_down' EXIT
  trap 'trap - EXIT INT TERM; cmd_down; exit 130' INT TERM
  cmd_up
  echo "[$label] --- full-flow-local billing tier (cargo billing:: $feature_args) ---"
  # Run the Rust L2 tier against the live mock. CYTO_TEST_NO_SKIP=1 turns the env-gate
  # self-skip into a HARD FAILURE, so the tier cannot pass vacuously; the sim env is
  # exported so the test reaches stripe-mock + signs with the shared local whsec.
  ( set -a
    export STRIPE_API_BASE=$STRIPE_API_BASE_LOCAL
    export STRIPE_WEBHOOK_SECRET=$WEBHOOK_SECRET_LOCAL
    export STRIPE_SECRET_KEY=$SECRET_KEY_LOCAL
    export CYTO_TEST_NO_SKIP=1
    set +a
    # The workspace manifest is at the REPO ROOT ($ROOT/Cargo.toml); src-app/server is
    # a member. Run the L2 tier (`billing::`) AND the injector self-tests
    # (`common::stripe_sim`) so the whole B0 correctness core runs under the live mock.
    # shellcheck disable=SC2086
    cargo test --manifest-path "$ROOT/Cargo.toml" -p cytoanalyst $feature_args \
      --test integration_tests -- --test-threads=1 --nocapture \
      billing:: common::stripe_sim
  ) || rc=1

  trap - INT TERM EXIT
  cmd_down || { echo "[$label] FAIL: teardown left containers"; rc=1; }
  if [ "$rc" -eq 0 ]; then echo "[$label] PASS"; else echo "[$label] FAIL"; fi
  return "$rc"
}

case "${1:-}" in
  up)           cmd_up ;;
  down)         cmd_down ;;
  env)          print_env ;;
  test-l1)      cmd_test_l1 ;;
  test-l2)      cmd_test_l2 ;;
  test-l2-saas) cmd_test_l2 "--features saas" ;;
  *) echo "usage: billing-sim.sh {up|down|env|test-l1|test-l2|test-l2-saas}" >&2; exit 2 ;;
esac
