#!/usr/bin/env python3
"""Build the TxResBench app's shipped file-validator material (file-validator node, ITEM-1,
extended by qa-fixes3 ITEM-3 with the example family + the separate predict table).

Reads the BENCHMARK tree at BUILD time only for the one byte-copy material (INV-1: the app
ships its own copy, generated by a script, never read at run time) and writes the six committed
files under `data/file-validator/` (PROV-FV-6 + the ITEM-3 growth):

    templates/patients.csv      header row only, the board's C-screen column spec
    templates/measurements.csv  header row only, the board's C-screen column spec
    examples/patients.csv       the synthetic example training patients table
    examples/measurements.csv   the synthetic example training measurements table
    examples/predict-measurements.csv  the synthetic example measurements of NEW patients to
                                predict (same markers; no outcomes — the N screen's shape)
    tidy-2.0.json               byte-identical provenance copy of the benchmark's machine-readable
                                tidy rule set (dev/code/benchmark/analysis-engine/contract/tidy/2.0.json)

The templates are constants (DEC-5/board spec); the example family is SYNTHESIZED here from a
seeded simulator (qa-fixes3 ITEM-3, DEC-1: small, seeded, synthetic, produced by the app's own
generator — never real data, never the benchmark tree): M1/M2/M3 markers in `a.u.`, ids `J*`,
draw days before (−28/−14) and during (0..56) treatment with follow-up draws, outcomes for
survival (pfs/os) AND response (responder/response_day), and marker trajectories that drive the
outcomes a little (the generator asserts their separation, so the trained predictions are never
constant). The simulator is parameterized per mode: the REAL mode writes the shipped family
(100 training patients, 15 predict patients, 3 markers), the FIXTURE mode writes the tiny
fixture family (3 patients, 2 markers, the node's own legacy scale) so the parity fixtures stay
small. Output is deterministic (fixed seeds, MT19937 — stable across Python 3.x); no clock, no
machine paths, no network in the material.
Nothing is read from `restricted/`, `datasets/`, `results/` or `analysis-catalog/` (INV-4).

Usage:
    python3 scripts/file-validator/gen_material.py [--out data/file-validator] [--fixtures]
        --fixtures        generate the small fixture family + read the fixture tidy contract
                          (scripts/file-validator/fixtures/contract/...); the default --out
                          becomes scripts/file-validator/fixtures/out (scratch)
        --check           regenerate in memory and byte-compare every file with the committed
                          material; exit 1 naming the first difference on any mismatch
                          (real mode: the file-validator --out dir; fixture mode:
                          scripts/file-validator/fixtures/expected/)
        --selftest        run the generator's own invariant checks against the fixture registry
                          (TEST-FV-14/TEST-FV-16 fixture legs) and exit 0/1
        --print-provenance  print the source facts (paths, source git commit, counts, tracked
                          status) as JSON to stdout; the only output that carries a timestamp,
                          pinned by SOURCE_DATE_EPOCH (method-catalogue precedent)
        --root DIR        benchmark tree root (default SIGTRANS_ROOT or /data/share/pbya/sigtrans)
        SOURCE_DATE_EPOCH timestamp override for the --print-provenance `generated_at`

Reproducibility (SOURCE_DATE_EPOCH semantics): the six shipped files are timestamp-free by
design (provenance lives in the module README, PROV-FV-6), so a fresh generation is
byte-identical to the committed material regardless of the clock; the only timestamp anywhere is
the `generated_at` field of `--print-provenance`. No network, no machine paths in the material.
Hygiene (INV-7): every emitted byte is scanned — any http(s):// literal, case-insensitive
`stud(y|ies)` token or status/placeholder token (placeholder / in progress / todo / fixme / wip)
aborts the run with a named error, never silently shipped; the example bytes are additionally
scanned for `restricted` / `GENIE` / `BPC` (INV-4: synthetic data only).
"""
