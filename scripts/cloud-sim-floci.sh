#!/usr/bin/env bash
# cloud-sim-floci.sh — the floci.io cloud-sim substrate (epic compute-storage).
#
# floci.io (https://floci.io — MIT, "AWS Local Emulator", no cloud account) is THE
# AWS half of the standardized cloud-sim substrate (paired with floci-gcp for the
# GCS + GKE-k3s half). ONE tool backs BOTH downstream AWS legs:
#
#   * S3  — the AWS S3 wire protocol on :4566 (real object store, dummy creds).
#           Backs the T2 ObjectStore contract (`s3_contract_test.rs`) UNCHANGED —
#           it reads the SAME S3_ENDPOINT/AWS_*/CYTO_WORKSTORE_S3_BUCKET contract.
#   * EKS — `aws eks create-cluster` spins up a REAL k3s node (Docker-backed,
#           rancher/k3s), yielding a real kubeconfig for the T3 KubernetesBackend
#           (`sandbox/kubernetes_backend_test.rs`) — a real Docker-backed k3s node.
#
# floci is AWS-focused and emulates NO native-GCS API, so the native-GCS legs run on
# the floci-gcp half (cloud-sim-floci-gcp.sh). This substrate covers S3 + k8s.
#
# It is credential-free (static dummy AWS keys, loopback-only :4566) and runs the
# no-cloud-credentials guard (cloud-sim-guard.sh) FIRST in every test tier — so a
# green run is a real portability proof.
#
# Subcommands:
#   up            start the floci container, pre-create the canonical S3 bucket,
#                 write the env contract. Idempotent.
#   down          stop+remove the floci container AND any EKS k3s / ECR sibling
#                 containers it spawned; remove the env + kubeconfig files. Idempotent.
#   env           print the env contract (also written to the env file by `up`)
#   bucket        (re)create the canonical bucket, idempotently
#   smoke         S3 reachability/contract smoke (curl PUT/GET on :4566)
#   eks-up        create VPC+subnet, `aws eks create-cluster`, wait ACTIVE, write kubeconfig
#   eks-down      delete the EKS cluster (removes the k3s + ECR sibling containers)
#   contract-s3   the ACCEPTANCE tier: guard -> up -> run the S3 ObjectStore contract
#                 suite (`s3_contract_test.rs`, saas) against floci's S3 -> down
#   contract-k8s  guard -> up -> eks-up -> run the KubernetesBackend contract test
#                 against floci's k3s -> eks-down -> down  (needs aws CLI + kubectl)
#   test          fail-closed tier: guard -> up -> smoke -> down (fast, no cargo)
#
# Env contract PROV-T1-4, guard-first PROV-T1-5 — floci is THE AWS half of the
# standardized substrate, paired with floci-gcp for the GCS + GKE half.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${CYTO_FLOCI_ENV_FILE:-$ROOT/src-app/cloud-sim/.floci-sim.env}"
GUARD="$ROOT/scripts/cloud-sim-guard.sh"

# --- the canonical endpoint-override env contract (PROV-T1-4, floci flavour) ---
FLOCI_IMAGE="${CYTO_FLOCI_IMAGE:-floci/floci:latest}"
FLOCI_NAME="${CYTO_FLOCI_NAME:-cyto-floci}"
FLOCI_PORT="${CYTO_FLOCI_PORT:-4566}"
S3_ENDPOINT="http://127.0.0.1:${FLOCI_PORT}"
# Static DUMMY creds — floci accepts any keys; these dummy keys are chosen so
# the no-cloud-credentials guard (which rejects AKIA/ASIA real keys) passes.
ACCESS_KEY="${CYTO_CLOUD_SIM_ACCESS_KEY:-cyto-sim}"
SECRET_KEY="${CYTO_CLOUD_SIM_SECRET_KEY:-cyto-sim-secret}"
AWS_REGION_V="${AWS_REGION:-us-east-1}"
BUCKET="${CYTO_WORKSTORE_S3_BUCKET:-cyto-worklab}"
EKS_CLUSTER="${CYTO_FLOCI_EKS_CLUSTER:-cyto-floci}"
KUBECONFIG_FILE="${KUBECONFIG:-$ROOT/src-app/cloud-sim/.floci-kube-config}"

say() { echo "[floci-sim] $*" >&2; }
die() { echo "[floci-sim] FAIL: $*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "'$1' not on PATH${2:+ — $2}"; }

# curl helpers so S3 needs NO aws/mc client (path-style, floci accepts unsigned).
s3_curl() { curl -s -o /dev/null -w '%{http_code}' --max-time 10 "$@"; }

wait_s3() {
  local i
  for i in $(seq 1 60); do
    if curl -fsS --max-time 2 -o /dev/null "$S3_ENDPOINT/_localstack/health" 2>/dev/null; then return 0; fi
    sleep 1
  done
  return 1
}

create_bucket() {
  # 200 on HEAD => exists (no-op); else PUT create (200/409 both ok).
  if [ "$(s3_curl -I "$S3_ENDPOINT/$BUCKET")" = "200" ]; then
    say "s3: bucket '$BUCKET' already present (idempotent no-op)"; return 0
  fi
  local code; code="$(s3_curl -X PUT "$S3_ENDPOINT/$BUCKET")"
  case "$code" in
    200|409) say "s3: bucket '$BUCKET' ready (http $code)" ;;
    *) die "s3: bucket create returned http $code" ;;
  esac
}

write_env_file() {
  cat > "$ENV_FILE" <<EOF
# GENERATED by scripts/cloud-sim-floci.sh — the floci.io endpoint-override env
# contract (PROV-T1-4). Source it to point an ObjectStore / compute backend at the
# local floci substrate:
#   set -a; source src-app/cloud-sim/.floci-sim.env; set +a
# Loopback-only + static dummy creds — no cloud account (DE-INV-13).
# floci emulates S3 + EKS; it does NOT emulate native GCS — the native-GCS legs
# run on the floci-gcp half (cloud-sim-floci-gcp.sh), so STORAGE_EMULATOR_HOST is unset
# here (the s3_contract_test GCS legs then loud-skip, as designed).
export CYTO_WORKSTORE_BACKEND=s3
export S3_ENDPOINT=$S3_ENDPOINT
export AWS_ACCESS_KEY_ID=$ACCESS_KEY
export AWS_SECRET_ACCESS_KEY=$SECRET_KEY
export AWS_REGION=$AWS_REGION_V
export AWS_DEFAULT_REGION=$AWS_REGION_V
export CYTO_WORKSTORE_S3_BUCKET=$BUCKET
export CYTO_COMPUTE_BACKEND=kubernetes
export KUBECONFIG=$KUBECONFIG_FILE
EOF
  say "wrote env contract → $ENV_FILE"
}

print_env() {
  cat <<EOF
CYTO_WORKSTORE_BACKEND=s3
S3_ENDPOINT=$S3_ENDPOINT
AWS_ACCESS_KEY_ID=$ACCESS_KEY
AWS_SECRET_ACCESS_KEY=$SECRET_KEY
AWS_REGION=$AWS_REGION_V
AWS_DEFAULT_REGION=$AWS_REGION_V
CYTO_WORKSTORE_S3_BUCKET=$BUCKET
CYTO_COMPUTE_BACKEND=kubernetes
KUBECONFIG=$KUBECONFIG_FILE
EOF
}

cmd_up() {
  need docker; need curl
  if docker ps --filter "name=^/${FLOCI_NAME}$" --format '{{.Names}}' 2>/dev/null | grep -qx "$FLOCI_NAME"; then
    say "floci container '$FLOCI_NAME' already running (idempotent)"
  else
    docker rm -f "$FLOCI_NAME" >/dev/null 2>&1 || true
    say "starting floci ($FLOCI_IMAGE) on :$FLOCI_PORT …"
    # Bind to LOOPBACK only — the "loopback-only :4566" (DE-INV-13) property must be
    # enforced by the publish, not just asserted; 0.0.0.0 would expose floci on the LAN.
    docker run -d --name "$FLOCI_NAME" -p "127.0.0.1:${FLOCI_PORT}:4566" \
      -v /var/run/docker.sock:/var/run/docker.sock -u root "$FLOCI_IMAGE" >/dev/null 2>&1 \
      || die "docker run floci failed"
  fi
  say "waiting for S3 ($S3_ENDPOINT) …"; wait_s3 || { docker logs --tail 30 "$FLOCI_NAME" >&2 2>&1; die "floci did not become ready"; }
  create_bucket
  write_env_file
  say "UP. floci substrate ready. Source the env: 'set -a; source $ENV_FILE; set +a'"
}

# Remove any k3s / ECR sibling containers floci spawned for an EKS cluster.
remove_eks_siblings() {
  local c
  for c in $(docker ps -aq --filter "name=floci-eks-" --filter "name=floci-ecr-" 2>/dev/null); do
    docker rm -f "$c" >/dev/null 2>&1 || true
  done
}

cmd_down() {
  need docker
  # Best-effort clean EKS delete first (frees the k3s node) if floci is still up.
  if docker ps --filter "name=^/${FLOCI_NAME}$" -q 2>/dev/null | grep -q .; then
    cmd_eks_down >/dev/null 2>&1 || true
  fi
  docker rm -f "$FLOCI_NAME" >/dev/null 2>&1 || true
  remove_eks_siblings
  rm -f "$ENV_FILE" "$KUBECONFIG_FILE" 2>/dev/null || true
  # VERIFY — never print DOWN over a survivor.
  if docker ps -aq --filter "name=^/${FLOCI_NAME}$" 2>/dev/null | grep -q . \
     || docker ps -aq --filter "name=floci-eks-" --filter "name=floci-ecr-" 2>/dev/null | grep -q .; then
    say "WARN: floci container(s) SURVIVED teardown — 'docker rm -f $FLOCI_NAME' + remove floci-eks-*/floci-ecr-* by hand."
    return 1
  fi
  say "DOWN. floci substrate removed."
  return 0
}

cmd_smoke() {
  need curl
  local key="probe/$$-$(date +%s).txt"
  [ "$(s3_curl -X PUT "$S3_ENDPOINT/$BUCKET/$key" --data 'cyto-floci-s3-probe')" = "200" ] \
    || die "s3 smoke: PUT failed"
  local got; got="$(curl -fsS --max-time 5 "$S3_ENDPOINT/$BUCKET/$key" 2>/dev/null)"
  s3_curl -X DELETE "$S3_ENDPOINT/$BUCKET/$key" >/dev/null 2>&1 || true
  [ "$got" = "cyto-floci-s3-probe" ] || die "s3 smoke: GET body mismatch ('$got')"
  say "s3 smoke: PUT/GET OK on floci S3 (:$FLOCI_PORT)"
}

# --- EKS -> real k3s (PROV-T3-1 substrate; the kind drop-in) -----------------
cmd_eks_up() {
  need aws "floci EKS is driven by the AWS CLI — https://aws.amazon.com/cli/"
  need kubectl "install kubectl — https://kubernetes.io/docs/tasks/tools/"
  export AWS_ACCESS_KEY_ID="$ACCESS_KEY" AWS_SECRET_ACCESS_KEY="$SECRET_KEY"
  export AWS_REGION="$AWS_REGION_V" AWS_DEFAULT_REGION="$AWS_REGION_V"
  local EP="--endpoint-url $S3_ENDPOINT"
  if [ "$(aws $EP eks describe-cluster --name "$EKS_CLUSTER" --query 'cluster.status' --output text 2>/dev/null)" = "ACTIVE" ]; then
    say "eks: cluster '$EKS_CLUSTER' already ACTIVE (idempotent)"
  else
    say "eks: creating VPC+subnet …"
    local vpc sub
    vpc="$(aws $EP ec2 create-vpc --cidr-block 10.0.0.0/16 --query 'Vpc.VpcId' --output text 2>/dev/null)" || die "eks: create-vpc failed"
    sub="$(aws $EP ec2 create-subnet --vpc-id "$vpc" --cidr-block 10.0.1.0/24 --query 'Subnet.SubnetId' --output text 2>/dev/null)" || die "eks: create-subnet failed"
    say "eks: create-cluster '$EKS_CLUSTER' (spins a real k3s node) …"
    aws $EP eks create-cluster --name "$EKS_CLUSTER" \
      --role-arn arn:aws:iam::000000000000:role/eks \
      --resources-vpc-config "subnetIds=$sub" >/dev/null 2>&1 || die "eks: create-cluster failed"
    local i st
    for i in $(seq 1 60); do
      st="$(aws $EP eks describe-cluster --name "$EKS_CLUSTER" --query 'cluster.status' --output text 2>/dev/null)"
      [ "$st" = "ACTIVE" ] && break
      sleep 2
    done
    [ "$st" = "ACTIVE" ] || die "eks: cluster did not reach ACTIVE (last status: ${st:-none})"
  fi
  aws $EP eks update-kubeconfig --name "$EKS_CLUSTER" --kubeconfig "$KUBECONFIG_FILE" >/dev/null 2>&1 \
    || die "eks: update-kubeconfig failed"
  KUBECONFIG="$KUBECONFIG_FILE" kubectl get nodes >/dev/null 2>&1 || die "eks: k3s node not reachable via kubectl"
  say "eks: k3s cluster ACTIVE, kubeconfig → $KUBECONFIG_FILE"
}

cmd_eks_down() {
  command -v aws >/dev/null 2>&1 || { remove_eks_siblings; return 0; }
  export AWS_ACCESS_KEY_ID="$ACCESS_KEY" AWS_SECRET_ACCESS_KEY="$SECRET_KEY"
  export AWS_REGION="$AWS_REGION_V" AWS_DEFAULT_REGION="$AWS_REGION_V"
  aws --endpoint-url "$S3_ENDPOINT" eks delete-cluster --name "$EKS_CLUSTER" >/dev/null 2>&1 || true
  remove_eks_siblings
  rm -f "$KUBECONFIG_FILE" 2>/dev/null || true
  say "eks: cluster '$EKS_CLUSTER' deleted (k3s/ECR siblings removed)"
}

run_guard() {
  # TEST-2 (INV-1): the no-cloud-credentials guard runs FIRST in every test tier;
  # `bash scripts/cloud-sim-guard.sh --selftest` proves it fails on a planted real cred.
  echo "[floci-sim] guard: refusing any real cloud credential/endpoint (INV-1)" >&2
  bash "$GUARD" || die "no-cloud-credentials guard REFUSED the env — a real cloud cred/endpoint is present (INV-1)"
}

# --- the S3 ObjectStore contract ACCEPTANCE tier ----------------------------
cmd_contract_s3() {
  need docker; need curl; need cargo
  run_guard
  trap 'cmd_down' EXIT
  trap 'trap - EXIT INT TERM; cmd_down; exit 130' INT TERM
  cmd_up
  # TEST-1 (INV-2): the full S3 ObjectStore contract suite against floci's REAL S3.
  say "running the S3 ObjectStore contract suite (s3_contract_test.rs, saas) against floci …"
  # shellcheck disable=SC1090
  set -a; . "$ENV_FILE"; set +a
  # STORAGE_EMULATOR_HOST intentionally unset → the native-GCS legs loud-skip.
  local rc=0
  ( cd "$ROOT" && cargo test -p cytoanalyst --features saas --test integration_tests \
      -- workstore::s3_contract --test-threads=1 ) || rc=1
  trap - INT TERM EXIT
  cmd_down || rc=1
  if [ "$rc" -eq 0 ]; then echo "[floci-sim] contract-s3 PASS"; else echo "[floci-sim] contract-s3 FAIL"; fi
  return "$rc"
}

# --- the KubernetesBackend contract tier (EKS -> k3s) -----------------------
cmd_contract_k8s() {
  need docker; need curl; need cargo; need aws; need kubectl
  run_guard
  trap 'cmd_down' EXIT
  trap 'trap - EXIT INT TERM; cmd_down; exit 130' INT TERM
  cmd_up
  cmd_eks_up
  # TEST-3 (INV-3): the EXISTING KubernetesBackend test, unchanged, against floci's k3s.
  say "running the KubernetesBackend contract test against floci's k3s …"
  set -a; . "$ENV_FILE"; set +a
  export KUBECONFIG="$KUBECONFIG_FILE"
  export CYTO_WORKER_IMAGE="${CYTO_WORKER_IMAGE:-busybox:latest}"
  local rc=0
  ( cd "$ROOT" && cargo test -p cytoanalyst --features saas --test integration_tests \
      sandbox::kubernetes_backend -- --test-threads=1 ) || rc=1
  trap - INT TERM EXIT
  cmd_down || rc=1
  if [ "$rc" -eq 0 ]; then echo "[floci-sim] contract-k8s PASS"; else echo "[floci-sim] contract-k8s FAIL"; fi
  return "$rc"
}

cmd_test() {
  # TEST-4: the fast fail-closed tier — guard → up → S3 smoke → idempotent re-up →
  # verify-teardown, sweeping every floci container (the `just cloud-sim-test-floci` family).
  need docker; need curl
  run_guard
  local rc=0
  trap 'cmd_down' EXIT
  trap 'trap - EXIT INT TERM; cmd_down; exit 130' INT TERM
  cmd_up
  smoke_env
  echo "[floci-sim] --- S3 reachability/contract smoke ---"
  cmd_smoke || rc=1
  # idempotency: a second up must not error on the already-present bucket
  echo "[floci-sim] idempotency: re-running up on a live stack …"
  cmd_up || rc=1
  trap - INT TERM EXIT
  cmd_down || { echo "[floci-sim] FAIL: teardown left containers"; rc=1; }
  if [ "$rc" -eq 0 ]; then echo "[floci-sim] test PASS"; else echo "[floci-sim] test FAIL"; fi
  return "$rc"
}

smoke_env() { grep -q "CYTO_WORKSTORE_S3_BUCKET=$BUCKET" "$ENV_FILE" 2>/dev/null || die "CYTO_WORKSTORE_S3_BUCKET not exported in $ENV_FILE"; }

case "${1:-}" in
  up)           cmd_up ;;
  down)         cmd_down ;;
  env)          print_env ;;
  bucket)       need curl; create_bucket ;;
  smoke)        cmd_smoke ;;
  eks-up)       cmd_eks_up ;;
  eks-down)     cmd_eks_down ;;
  contract-s3)  cmd_contract_s3 ;;
  contract-k8s) cmd_contract_k8s ;;
  test)         cmd_test ;;
  *) echo "usage: cloud-sim-floci.sh {up|down|env|bucket|smoke|eks-up|eks-down|contract-s3|contract-k8s|test}" >&2; exit 2 ;;
esac
