#!/usr/bin/env node
// TEST-85 (visualize-pane ITEM-69) — the rename commit is MECHANICAL.
//
// ── What this is for ──────────────────────────────────────────────────────────────────
//
// ITEM-69 moves two directories and rewrites the path strings that name them:
//
//     src-app/packages/{viz,dock}  →  src-app/libs/*        (the npm libs VACATE)
//     src-app/processors/          →  src-app/packages/     (the package tree MOVES)
//
// It is deliberately ONE commit, landed LAST, because a mechanical commit is
// resolvable by RE-RUNNING it: a rebase that conflicts on a renamed path is fixed by
// redoing the move, not by hand-merging hundreds of hunks. That property only holds if
// the commit really is mechanical — the moment one real edit rides along inside it, the
// re-run answer is wrong and the diff has to be read line by line instead.
//
// So this check states the property as a machine test rather than as a commit message
// promise: every changed line in the rename commit differs from its predecessor ONLY in
// the directory-name tokens the rename moves.
//
// ── The rule ──────────────────────────────────────────────────────────────────────────
//
// Normalise both sides of every modified line by collapsing the three moving tokens
// (`processors` / `packages` / `libs`) to one placeholder; the multiset of normalised
// REMOVED lines must equal the multiset of normalised ADDED lines, per file.
//
//   · It is a MULTISET, not a zip, because a rename reorders a SORTED file: the ledger
//     keys in `native-controls-baseline.json` move when `packages/viz/…` becomes
//     `libs/viz/…`, and a positional comparison would read that as content churn.
//   · It is EQUALITY of multisets, so a line that is added, deleted or edited in any
//     way OTHER than through those tokens fails — including a "while I'm here" comment
//     fix, which is exactly what this check exists to refuse.
//   · Pure RENAMES (git `R…`) are the point of the commit and carry no line diff; they
//     are counted and reported, never inspected.
//
// ── The one exemption, and why it is not a hole ───────────────────────────────────────
//
// `package-lock.json` is REGENERATED by npm, not edited: moving a workspace makes npm
// rewrite the `workspaces` globs, add the new `src-app/libs/*` entries and mark the
// vacated ones `"extraneous": true`. Those are insertions with no removed counterpart,
// so no substitution rule can explain them. It is exempted BY NAME (never by pattern),
// and the exemption is narrow: it is a generated lockfile whose content is derived from
// `package.json`, which is itself checked like every other file.
//
// Usage:
//   node scripts/check-rename-mechanical.mjs                 # auto-locate on origin/main..HEAD
//   node scripts/check-rename-mechanical.mjs --commit <ref>
//   node scripts/check-rename-mechanical.mjs --base origin/main
//   node scripts/check-rename-mechanical.mjs --repo <dir> --commit <ref>   # tests only
//
// Exit 0 = mechanical (or: no rename commit on this branch — see NOTE below).
// Exit 1 = a non-path change rode along, with the offending lines printed.

import { execFileSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))

/** The repository to inspect. Defaults to this script's own repo — the real subject — and is
 *  overridable ONLY so `check-rename-mechanical.test.mjs` can drive THIS script against
 *  synthetic repositories where the answer is known. Without the seam a test can do no better
 *  than re-implement the rule and assert against its own copy, which proves nothing about the
 *  guard that actually runs. */
function repoArg() {
  const i = process.argv.indexOf('--repo')
  return i >= 0 && process.argv[i + 1] ? path.resolve(process.argv[i + 1]) : path.resolve(HERE, '../../..')
}
const REPO = repoArg()

/** The directory-name tokens the rename moves. Collapsing all three to one placeholder is
 *  what makes `processors/`→`packages/` and `packages/viz`→`libs/viz` both read as "no
 *  change" while any other edit on the same line still shows up. */
const MOVING_TOKENS = /\b(processors|packages|libs)\b/g
const PLACEHOLDER = '§'

/** Generated, not authored — see the header. Exempt BY NAME, never by pattern. */
const GENERATED = new Set(['package-lock.json'])

/**
 * THE CONTEXTS THAT MUST NOT MOVE — and the blind spot they close.
 *
 * `MOVING_TOKENS` collapses `processors` / `packages` / `libs` to ONE placeholder, which is
 * what lets a directory move read as "no change". The cost is that it also erases the
 * DIRECTION: a line rewritten the WRONG way normalises to exactly the same placeholder as a
 * line rewritten the right way, so the multiset stays balanced and the commit certifies as
 * "0 non-path changes". The one genuinely dangerous class of mistake in this rename is
 * precisely that — the word `processors` names several different things and only ONE of them
 * moved:
 *
 *   · `src-app/processors/`      — the SOURCE tree. It MOVED to `src-app/packages/`.
 *   · `<data_root>/processors/`  — the DEPLOYED extraction root. It did NOT move (DEC-8b);
 *                                  rewriting it silently repoints every runtime lookup.
 *   · `/api/processors/*`        — the REST namespace. Renaming it breaks every client.
 *   · `modules/processors`, `/settings/processors` — the UI module id and its route.
 *
 * A textual sweep cannot tell them apart, so each of the spellings below must SURVIVE AS A
 * COUNT: the number of occurrences must be identical on the removed and added sides of the
 * commit. A correct rename never touches one; a wrong substitution drops the count and fails
 * HERE, naming the context.
 *
 * TWO limits, named rather than hidden. (a) The count is per FILE, so removing an occurrence
 * on one line and adding one elsewhere in the same file balances — the multiset rule still
 * has to accept that file for it to pass, but this check alone would not catch it. (b) The
 * `packages`→`libs` half of the move is guarded only where a protected spelling contains
 * `packages` (`/api/processors/packages`); a `packages` occurrence in some other protected
 * role would need its own entry here.
 *
 * Counts, not presence: a protected spelling may legitimately appear on a line that also
 * carries a moving path (a test that asserts the source moved while the data root did not),
 * so "it appears on both sides" is too weak — the number has to be preserved.
 */
const PROTECTED_CONTEXTS = [
  { what: 'the REST namespace', find: /\/api\/processors/g },
  // The `packages` SEGMENT of the route is protected too: it is a route word, not the moved
  // directory, and rewriting it to `libs` leaves the `/api/processors` count above unchanged.
  { what: 'the REST namespace’s packages route', find: /\/api\/processors\/packages/g },
  { what: 'the deployed extraction root', find: /<data_root>\/processors/g },
  // Anchored on the RECEIVER, not on the join: `src_app_dir().join("processors")` is the
  // SOURCE tree and DID move, while `data_root()/data_dir().join("processors")` is the
  // deployed root and did not. A pattern matching the join alone flags both and is therefore
  // useless — it fires on the very commit it is supposed to bless. This is deliberately
  // partial: a join whose receiver is a local (`dir.join("processors")`) is invisible here,
  // and the prose + route counts below are what cover the rest. A guard that names its blind
  // spot is worth more than one that pretends it has none.
  { what: 'a path join onto the DEPLOYED data root', find: /\b(data_root\(\)|data_dir\(\)|data_dir)\.join\(["']processors["']\)/g },
  { what: 'the UI module id', find: /modules\/processors/g },
  { what: 'the settings route', find: /\/settings\/processors/g },
]

/** How many times each protected spelling occurs across `lines`. */
function protectedCounts(lines) {
  const out = new Map()
  for (const { what, find } of PROTECTED_CONTEXTS) {
    let n = 0
    for (const line of lines) n += (line.match(find) ?? []).length
    out.set(what, n)
  }
  return out
}

/** The subject marker that identifies a RENAME commit when none is given.
 *
 *  It is `ITEM-69: rename`, not the bare item id, and the difference matters: the item
 *  also ships the tests that PROVE the rename, and those are ordinary authored commits
 *  that must NOT be judged by this rule. A marker matching the item alone would fail on
 *  its own test suite — which is a check confused about its own subject, not a finding. */
const MARKER = 'ITEM-69: rename'

function git(args) {
  return execFileSync('git', args, { cwd: REPO, encoding: 'utf8', maxBuffer: 1 << 28 })
}

function arg(name, fallback) {
  const i = process.argv.indexOf(name)
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : fallback
}

const base = arg('--base', 'origin/main')
const explicit = arg('--commit', null)

/** @type {string[]} */
let commits = []
if (explicit) {
  commits = [explicit]
} else {
  let log = ''
  try {
    log = git(['log', '--format=%H%x00%s', `${base}..HEAD`])
  } catch {
    console.log(`[check-rename-mechanical] NOTE — cannot read ${base}..HEAD; nothing to check.`)
    process.exit(0)
  }
  // EVERY commit carrying the marker, not the first one found. The rename landed as the
  // big move plus a follow-up for the path joins a textual rewrite cannot see (a path
  // built by joining SEGMENTS never contains the directory name as a substring), and a
  // check that stopped at one match would silently certify whichever it happened to pick.
  commits = log
    .split('\n')
    .filter(Boolean)
    .map(l => l.split('\0'))
    .filter(([, subject]) => subject.includes(MARKER))
    .map(([sha]) => sha)
    .reverse()
  if (commits.length === 0) {
    // NOT a failure. On a branch that has not landed the rename (or after it has been
    // merged and this script runs from main), there is simply no subject to check. The
    // check is a property of a COMMIT; asserting the commit exists is a different claim,
    // and one a pre-commit run could never satisfy.
    console.log(
      `[check-rename-mechanical] NOTE — no commit with "${MARKER}" in its subject on ${base}..HEAD; nothing to check.`,
    )
    process.exit(0)
  }
}

const norm = s => s.replace(MOVING_TOKENS, PLACEHOLDER)
let bad = 0

for (const commit of commits) {
  const subject = git(['log', '-1', '--format=%s', commit]).trim()
  const status = git(['diff-tree', '--no-commit-id', '-r', '-M', '--name-status', '-z', commit])
    .split('\0')
    .filter(Boolean)

  // `--name-status -z` emits R-entries as three fields (status, old, new) and every other
  // status as two, so the stream is walked rather than paired blindly.
  const renamed = []
  const modified = []
  for (let i = 0; i < status.length; ) {
    const st = status[i]
    if (st.startsWith('R') || st.startsWith('C')) {
      renamed.push([status[i + 1], status[i + 2]])
      i += 3
    } else {
      // A/M/D all go through the line check: an ADDED file has no removed counterpart for
      // any of its lines, so a new file rides along only by failing this.
      modified.push(status[i + 1])
      i += 2
    }
  }

  const problems = []
  for (const file of modified) {
    if (GENERATED.has(file)) continue
    const diff = git(['diff', '-U0', '-M', `${commit}^`, commit, '--', file])
    /** @type {Map<string, number>} */
    const bag = new Map()
    const bump = (k, d) => bag.set(k, (bag.get(k) ?? 0) + d)
    const removedRaw = []
    const addedRaw = []
    for (const line of diff.split('\n')) {
      if (line.startsWith('+++') || line.startsWith('---')) continue
      if (line.startsWith('-')) {
        removedRaw.push(line.slice(1))
        bump(norm(line.slice(1)), -1)
      } else if (line.startsWith('+')) {
        addedRaw.push(line.slice(1))
        bump(norm(line.slice(1)), +1)
      }
    }
    const unbalanced = [...bag.entries()].filter(([, n]) => n !== 0)
    // The DIRECTION check the placeholder cannot make — see `PROTECTED_CONTEXTS`.
    const before = protectedCounts(removedRaw)
    const after = protectedCounts(addedRaw)
    const moved = [...before.entries()]
      .filter(([what, n]) => n !== after.get(what))
      .map(([what, n]) => ({ what, before: n, after: after.get(what) ?? 0 }))
    if (unbalanced.length || moved.length) problems.push({ file, unbalanced, moved })
  }

  if (problems.length) {
    bad += 1
    console.error(`\n✖ check-rename-mechanical: ${commit.slice(0, 12)} "${subject}" is NOT mechanical.\n`)
    for (const p of problems) {
      console.error(`  ${p.file}`)
      for (const m of p.moved) {
        console.error(
          `    PROTECTED CONTEXT CHANGED — ${m.what}: ${m.before} occurrence(s) on the removed ` +
            `side, ${m.after} on the added side. Only src-app/processors/ (the SOURCE tree) moves; ` +
            `this one does not, so its count must be identical. (A count that ROSE means the ` +
            `commit ADDED such a line rather than rewriting one — still not mechanical.)`,
        )
      }
      for (const [k, n] of p.unbalanced.slice(0, 12)) {
        console.error(`    ${n > 0 ? 'ADDED' : 'REMOVED'} with no path-only counterpart: ${k.trim().slice(0, 160)}`)
      }
      if (p.unbalanced.length > 12) console.error(`    … ${p.unbalanced.length - 12} more`)
    }
  } else {
    console.log(
      `[check-rename-mechanical] OK — ${commit.slice(0, 12)} "${subject}": ` +
        `${renamed.length} pure rename(s), ${modified.length} path-string edit(s), 0 non-path changes.`,
    )
  }
}

if (bad > 0) {
  console.error(
    `\n  A rename commit must be re-runnable: every changed line differs ONLY in the moved\n` +
      `  directory names. Move the real edit into its own commit.\n`,
  )
  process.exit(1)
}
