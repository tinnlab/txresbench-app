/** The fixture CSV text (`predictions-<runId>.csv`'s content; the byte shape is
 *  the provider's — CONS-UR-5: this node never re-parses it). */
function fxCsvText(runId: string, specs: FxMethodSpec[]): string {
  const header = ['patient_id', ...specs.map(s => s.methodId), 'notes'].join(',')
  const rows = Array.from({ length: 8 }, (_, i) => {
    const p = i + 1
    const values = specs.map((_, m) => fxHChance(p, m).toFixed(6))
    return [fxPatientId(p + 8), ...values, ''].join(',')
  })
  return `${header}\n${rows.join('\n')}\n`
}

