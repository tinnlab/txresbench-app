// ── the abstain rule (a few values empty with a note — INV-2's abstain affordance) ──

/** The abstain note the fixture carries (synthetic copy, never a board string). */
export const TXR_ABSTAIN_NOTE = 'no draw after decision day'

/** The dynamic-risk column positions of TXR_G_SPECS (the pfs-tab abstain set). */
const FX_DYNAMIC = new Set([1, 3, 6, 7])
/** The response-probability column positions of TXR_G_SPECS (the pfs tab's second abstain set). */
const FX_RESPONSE_PROB = new Set([0, 4, 9])

/** Whether one G value (patient p, method m) abstains (deterministic, sparse). */
export function fxGAbstains(p: number, m: number): boolean {
  return (FX_DYNAMIC.has(m) && p % 7 === 0) || (FX_RESPONSE_PROB.has(m) && p % 11 === 0)
}

// ── the generated-array bridge (DRIFT-1 ITEM-2 #3's `number | null[]` artifact) ──

/** The openapi-generator `Vec<Option<T>>` artifact → the real array shape. */
function wireArray<T>(values: Array<T | null>): T | null[] {
  return values as unknown as T | null[]
}

/** The per-patient mean (0–1) — the provider's `average` field of a fixture. */
function meanOf(values: Array<number | null>): number | null {
  const present = values.filter((v): v is number => v !== null)
  if (present.length === 0) return null
  return present.reduce((a, b) => a + b, 0) / present.length
}

// ── the predictions response builders ──

/**
 * One prediction column built by a per-value chance function (the G spread
 * family, the H correlated pair, or any fixture's own) with an optional
 * abstain rule carrying the fixture note.
 */
function fxColumn(
  spec: FxMethodSpec,
  m: number,
  patients: string[],
  chance: (p: number, m: number) => number,
  abstains: (p: number, m: number) => boolean = () => false,
): TxrPredictionsResponse['methods'][number] {
  const probabilities: Array<number | null> = []
  const notes: Array<string | null> = []
  for (let p = 1; p <= patients.length; p += 1) {
    if (abstains(p, m)) {
      probabilities.push(null)
      notes.push(TXR_ABSTAIN_NOTE)
    } else {
      probabilities.push(chance(p, m))
      notes.push(null)
    }
  }
  return {
    method_id: spec.methodId,
    label: spec.methodId,
    group: spec.group,
    group_label: spec.groupLabel,
    task: spec.task,
    prob_source: spec.probSource,
    coverage: { scored: patients.length, eligible: patients.length, fraction: 1 },
    probabilities: wireArray(probabilities),
    notes: wireArray(notes),
  }
}

/** The predictions of the G run (the first `count` methods of TXR_G_SPECS). */
export function fxGPredictions(runId: string, count: number, patientCount = TXR_G_PATIENTS): TxrPredictionsResponse {
  const patients = fxPatients(patientCount)
  const methods = TXR_G_SPECS.slice(0, count).map((spec, m) => fxColumn(spec, m, patients, fxChance, fxGAbstains))
  const average = patients.map((_, i) => {
    const p = i + 1
    return meanOf(methods.map((_, m) => (fxGAbstains(p, m) ? null : fxChance(p, m))))
  })
  return {
    run_id: runId,
    endpoint: 'pfs',
    horizon: TXR_HORIZON,
    patients,
    methods,
    average: wireArray(average),
    generated_at: '2026-09-03T09:00:00Z',
  }
}

