/** The zeroed counts — the derived source is the method rows (COUNT-UR / ITEM-5). */
function zeroCounts(): TxrRunCounts {
  return { waiting: 0, downloading: 0, running: 0, finished: 0, failed: 0, stopped: 0, skipped: 0, cannot_run: 0 }
}

function countsOf(methods: TxrRunMethod[]): TxrRunCounts {
  const counts = zeroCounts()
  for (const method of methods) counts[method.state] += 1
  return counts
}

/** One method row of a fixture run. */
function methodRow(spec: FxMethodSpec, state: TxrRunMethod['state'], over: Partial<TxrRunMethod> = {}): TxrRunMethod {
  return {
    method_id: spec.methodId,
    label: spec.methodId,
    group: spec.group,
    group_label: spec.groupLabel,
    version: '0.1.0',
    state,
    bytes_downloaded: state === 'downloading' ? 42 : 0,
    bytes_total: state === 'downloading' ? 100 : undefined,
    coverage: state === 'finished' ? { scored: TXR_G_PATIENTS, eligible: TXR_G_PATIENTS, fraction: 1 } : undefined,
    prob_source: spec.probSource,
    task: spec.task,
    phase: state === 'running' ? 'predict' : state === 'finished' ? 'done' : undefined,
    elapsed_secs: state === 'finished' ? 40 : 5,
    started_at: '2026-09-03T08:50:00Z',
    finished_at: state === 'finished' ? '2026-09-03T08:50:40Z' : undefined,
    ...over,
  }
}

/** One produced-model record of a fixture run. */
function modelOf(methodId: string, trainedOn: number): TxrProducedModel {
  return {
    method_id: methodId,
    method_version: '0.1.0',
    model_out_digest: 'fx'.padEnd(64, 'a'),
    tree_sha256: 'fx'.padEnd(64, 'b'),
    dir: `Documents/TxResBench/models/${methodId}`,
    env: { base_digest: 'fx'.padEnd(64, 'c'), layer_digest: 'fx'.padEnd(64, 'd') },
    trained_on_patients: trainedOn,
    size_bytes: 8192,
  }
}

/** One fixture run detail (the builder's defaults are the G run's shape). */
function runDetail(over: Partial<TxrRunDetail> & { id: string; dir: string; status: TxrRunStatus; methods: TxrRunMethod[] }): TxrRunDetail {
  const { id, dir, status, methods, models: modelsOver, ...rest } = over
  const models =
    modelsOver ?? methods.filter(m => m.state === 'finished').map(m => modelOf(m.method_id, TXR_TRAINED_ON))
  return {
    id,
    dir,
    status,
    methods,
    models,
    config: { ...TXR_FX_CONFIG, ...rest.config },
    counts: rest.counts ?? countsOf(methods),
    cpus: 4,
    created_at: '2026-09-03T08:49:00Z',
    elapsed_secs: rest.elapsed_secs,
    input_summary: {
      markers: 3,
      patients: TXR_TRAINED_ON,
      predict_patients: rest.input_summary?.predict_patients,
      file_names: { measurements: 'measurements.csv', patients: 'patients.csv' },
      events: rest.input_summary?.events,
    },
    log_lines: rest.log_lines ?? 7,
    method_ids: methods.map(m => m.method_id),
    mode: rest.mode ?? 'train',
    model_ids: [],
    outcome: { endpoint: 'pfs', horizon: TXR_HORIZON, task_is_mixed: rest.outcome?.task_is_mixed ?? false },
    predictions_ready: rest.predictions_ready ?? methods.some(m => m.state === 'finished'),
    started_at: '2026-09-03T08:50:00Z',
    finished_at: status === 'finished' ? (rest.finished_at ?? '2026-09-03T09:01:00Z') : undefined,
    ...rest,
  }
}

