// ── the fixture value spread (a deterministic formula, never the boards' numbers) ──

/** The spread's lower bound (5 %). */
const FX_MIN = 5
/** The spread's modulus (values cycle 5..94 %). */
const FX_MOD = 90

/** One generated chance in percent (the fixed-spread formula, INV-5). */
function fxPercent(p: number, m: number): number {
  return FX_MIN + ((p * 61 + m * 23) % FX_MOD)
}

/** The G heatmap's probability (0–1) for patient `p`, method `m`. */
export function fxChance(p: number, m: number): number {
  return fxPercent(p, m) / 100
}

/** The H bar-table's probability (0–1): the second method is the first plus
 *  a small per-patient offset, clamped to the spread's window — the board's
 *  correlated two-column shape (mostly close, a few wider apart). */
export function fxHChance(p: number, m: number): number {
  if (m === 0) return fxPercent(p, 0) / 100
  const offset = ((p * 11) % 31) - 15
  return Math.max(FX_MIN, Math.min(FX_MIN + FX_MOD - 1, fxPercent(p, 0) + offset)) / 100
}

/** The deterministic patient id of the fixture spread (`S\d{4,}`, INV-5). */
export function fxPatientId(index: number): string {
  return `S${String(index).padStart(4, '0')}`
}

/** The fixture patient id list: `[S0001, …, S00NN]`. */
export function fxPatients(count: number): string[] {
  return Array.from({ length: count }, (_, i) => fxPatientId(i + 1))
}

