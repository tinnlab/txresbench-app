/**
 * txrlist method-catalogue fetch hook — PROV-UI-LIST-3 (the half of the
 * adapter that talks to the wire; `buildMethodRows` is the pure join).
 *
 * `useMethodRows(inventory)` fetches `GET /api/methods` (the catalogue rows)
 * and `POST /api/methods/eligibility` (the verdicts for the host's current
 * analysis inventory) and joins them into the screen-E rows. It uses ONLY
 * the generated `ApiClient` (DEC-11) — no `fetch()`, no host literal, so
 * the network-allowlist guard stays green untouched (INV-4) — and the wire
 * shapes are the provider's generated types (never vendored, never
 * regenerated by this module).
 *
 * Fetch semantics:
 *
 * - The inventory is keyed by a STABLE JSON hash (its own content, keys
 *   recursively sorted, array order kept): two content-identical inventory
 *   objects — the object a host rebuilds on every render — hash to the same
 *   key and do NOT refetch (the plan's "same key → no refetch"). Only a
 *   content change, or an explicit `refetch()`, hits the endpoints again.
 * - Both endpoints are fetched in parallel and joined once; `loading` is
 *   true from the key change until the joined rows land (kept rows are the
 *   last successful set — the skeleton/error chrome is the component's).
 * - A failed fetch surfaces `error`; `refetch()` clears it and retries.
 * - An in-flight request is discarded when the key changes or the host
 *   unmounts (the effect's cancellation flag): only the newest key's
 *   response may write state (the plan's stale-response rule).
 */
import { useCallback, useEffect, useMemo, useState } from 'react'
import { ApiClient } from '@/api-client'
import type { InventoryEligibilityRequest } from '@/api-client/types'
import type { TxrListRow } from '../types'
import { buildMethodRows } from './methodRows'

export interface UseMethodRowsResult {
  /** The joined screen-E rows for the last loaded inventory. */
  rows: TxrListRow[]
  /** True from the inventory change until the response lands. */
  loading: boolean
  /** The fetch failure message, `null` when healthy. */
  error: string | null
  /** Re-fetch both endpoints for the current inventory. */
  refetch: () => void
}

/**
 * The canonical form of a wire payload: its plain values, with object keys
 * recursively sorted (array ORDER kept — a per-patient draw list's order is
 * content). Two payloads with the same canonical form hash identically.
 */
function canonicalize(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonicalize)
  if (value !== null && typeof value === 'object') {
    const out: Record<string, unknown> = {}
    for (const k of Object.keys(value as Record<string, unknown>).sort()) {
      out[k] = canonicalize((value as Record<string, unknown>)[k])
    }
    return out
  }
  return value
}

/**
 * The inventory's stable content key — the hook's refetch discriminator.
 * A host-rebuilt, content-identical object hashes to the same key.
 */
export function stableInventoryKey(inventory: InventoryEligibilityRequest): string {
  return JSON.stringify(canonicalize(inventory))
}

/**
 * The error line for the fetch (the Datasets-store idiom: the thrown
 * message, else the operation's constant).
 */
function errorMessage(err: unknown): string {
  return err instanceof Error ? err.message : 'Failed to load methods'
}

export function useMethodRows(inventory: InventoryEligibilityRequest): UseMethodRowsResult {
  const key = useMemo(() => stableInventoryKey(inventory), [inventory])
  const [rows, setRows] = useState<TxrListRow[]>([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [refresh, setRefresh] = useState(0)

  useEffect(() => {
    // The closure's `inventory` is the object this key was derived from, so
    // a content-identical rebuild (same key) never re-issues the request —
    // the effect is keyed on the hash, not the object identity.
    let cancelled = false
    setLoading(true)
    setError(null)
    void Promise.all([
      ApiClient.MethodCatalogue.list({}),
      ApiClient.MethodCatalogue.eligibility({ inventory }),
    ])
      .then(([list, eligibility]) => {
        if (cancelled) return
        setRows(buildMethodRows(list.methods, eligibility))
        setLoading(false)
      })
      .catch((err: unknown) => {
        if (cancelled) return
        setError(errorMessage(err))
        setLoading(false)
      })
    return () => {
      cancelled = true
    }
    // `inventory` is deliberately not a dependency: its content key is the
    // pair's cache discriminator, and a content-identical rebuild must not
    // re-issue the request (same key -> no refetch).
  }, [key, refresh])

  const refetch = useCallback(() => {
    setRefresh(count => count + 1)
  }, [])

  return { rows, loading, error, refetch }
}
