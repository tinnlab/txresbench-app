/**
 * txrmodels — the module's shared vocabulary types (PROV-UI-MODELS-3/4).
 *
 * The unions below are the host-state vocabulary of the two choice
 * screens: each chip and each sort option the boards draw has exactly one
 * id here, and the pure filter/sort functions in `lib` map the ids to
 * predicates and comparators. A host screen never spells a chip or sort as
 * a bare string outside these ids: a board option is added here once, then
 * in the page's chip/sort tables and the `lib` maps.
 *
 * `TxrModelsState` (PROV-UI-MODELS-3) is the module store's state shape:
 * the host-level state (selection, filters, sort, search, at-a-time, the
 * draft set name, the pending-Use model id, the open dialog, the per-card
 * download views) plus the data slices the three screens read (the
 * inventory from the intake GAP, the pretrained catalogue list, the saved
 * models + sets, the saved-model eligibility verdicts).
 *
 * The row-level shapes are NOT declared here: the D/I rows the module
 * builds are `txrlist`'s (`TxrListRow` / `TxrListSection` — the shared
 * component's contract, PROV-UI-LIST-2), and the server shapes the
 * builders join are the generated api-client's (`ModelSummary`,
 * `PretrainedSummary`, `ModelEligibilityResponse`,
 * `InventoryEligibilityRequest`, … — provider-owned, regenerated by the
 * providers, never copied or restated here). The formatters in
 * `lib/format.ts` read the generated vocabulary directly (`TxrTask`,
 * `TxrEndpoint`, `ModelProvenance`); the store does the same for the
 * eligibility and download statuses.
 */
import type {
  InventoryEligibilityRequest,
  ModelEligibility,
  ModelSummary,
  PretrainedDownloadStatus,
  PretrainedSummary,
  SetSummary,
} from '@/api-client/types'

/**
 * The chip row of screens D (All / Can run / Published rules / Learned by
 * the benchmark / Checked on 2 or more other cohorts) and I (All runs /
 * Can run / Same outcome as my file) — the boards' chip words, one id per
 * chip. `'all'` and `'can-run'` are the shared list's built-in counts; the
 * rest are host-made predicates (`lib/filters.ts`).
 */
export type TxrModelFilterId =
  | 'all'
  | 'can-run'
  | 'published'
  | 'learned'
  | 'checked-2-plus'
  | 'same-outcome'

/**
 * The sort options of screens D (Transfer to other cohorts / Patients
 * covered / Time to run) and I (Newest run first / Patients covered / Time
 * to run) — the boards' "Sort by" entries, one id per option. `'name'`
 * is reserved for the row-name ordering a host may want; the boards do not
 * draw it, so until ITEM-4's comparator table maps it the sort select never
 * offers it.
 */
export type TxrModelSortId =
  | 'transfer'
  | 'coverage'
  | 'time'
  | 'newest-run'
  | 'patients'
  | 'name'

/**
 * The dialog-state vocabulary (PROV-UI-MODELS-3): ONE host-level field
 * describes which modal is open — the three save dialogs (L / L2 / L3,
 * opened by the router-effect host on the EventBus events) and the per-row
 * dialogs (`card:<id>` — the D "Model card", `details:<id>` — the I row
 * "Details"). 'none' is the closed state; a new dialog replaces the field
 * (a second event never stacks a second dialog — the host's rule).
 */
export type TxrModelDialogId =
  | 'none'
  | 'save-set'
  | 'save-one'
  | 'saved'
  | `card:${string}`
  | `details:${string}`

/**
 * One card's download-view state (the D-screen download column, backed by
 * PROV-PC-6's download manager): `status` is the provider's
 * [`PretrainedDownloadStatus`] as reported — the wire vocabulary is used
 * verbatim, never restated, so a provider regen that reshapes it breaks
 * the typecheck here (the txrlist DEC-11 move) — and `error` is a request
 * failure the provider never reported (the Retry path; a provider failure
 * arrives as `status.state === 'failed'` with its own `error`).
 */
export interface TxrModelDownloadState {
  status: PretrainedDownloadStatus | null
  error: string | null
}

/**
 * The preferred key set of one screen: 'D' rows key `'ps:<catalogue_id>'`,
 * 'I' rows key the saved model uuid (DEC-8).
 */
export type TxrModelRowKey = string

/**
 * The module store's state (PROV-UI-MODELS-3). The d/i/j/pending state
 * touches the current analysis' file summary, so the store is NEVER
 * persisted: the engine is the durability point and the inventory belongs
 * to the intake store (PROV-UI-INTAKE-2's DEC-4 posture — a reload gives
 * a fresh state, nothing patient-adjacent in browser storage, INV-7).
 *
 * - `inventory` — the ONE `InventoryEligibilityRequest` object from the
 *   intake GAP (`IntakeSnapshot.validation.inventory`), passed to the
 *   eligibility endpoints verbatim (the ui-list DEC-15 ONE-builder pin);
 * - `pretrained` / `saved` — the D/I data slices with their load state;
 * - `eligibility` — the saved-models verdicts (PROV-MS-9): per-key entry
 *   (a key the response omitted maps to `null` — the row builder's
 *   defensive fallback, PROV-UI-MODELS-4) + the response totals;
 * - `selection` / `filters` / `sort` / `search` — the host list state the
 *   shared `TxrSelectList` is fed from (the LIST component owns none of
 *   it); `filters` is the set of ACTIVE chip ids (the filter chips are
 *   host predicates, `lib/filters.ts`);
 * - `atATime` — the bottom-bar "N run at a time" choice (the engine's
 *   default, PROV-EE-2);
 * - `draftName` — the L dialog's new-set name field;
 * - `pendingUseModelId` — the J "Use" handoff (DEC-10): the id the I
 *   screen preselects on mount, then clears;
 * - `dialog` — which modal is open (see `TxrModelDialogId`);
 * - `downloadState` — per-catalogue-id download views (see
 *   `TxrModelDownloadState`); absence of an entry = not started.
 */
export interface TxrModelsState {
  inventory: InventoryEligibilityRequest | null
  pretrained: {
    cards: PretrainedSummary[]
    loading: boolean
    error: string | null
  }
  saved: {
    summaries: ModelSummary[]
    sets: SetSummary[]
    loading: boolean
    error: string | null
  }
  eligibility: {
    byKey: ReadonlyMap<string, ModelEligibility | null>
    totals: { fit: number; some: number; cannot: number } | null
    loading: boolean
    error: string | null
  }
  selection: ReadonlySet<TxrModelRowKey>
  filters: TxrModelFilterId[]
  sort: TxrModelSortId
  search: string
  atATime: number
  draftName: string
  pendingUseModelId: string | null
  dialog: TxrModelDialogId
  downloadState: Record<string, TxrModelDownloadState>
}
